create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null check (char_length(username) between 3 and 24),
  bio text not null default '' check (char_length(bio) <= 160),
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);
create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  body text not null default '' check (char_length(body) <= 2000),
  image_url text,
  created_at timestamptz not null default now(),
  constraint post_has_content check (char_length(trim(body)) > 0 or image_url is not null)
);
create table if not exists public.likes (
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(post_id,user_id)
);
create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 500),
  created_at timestamptz not null default now()
);
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  receiver_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 1000),
  created_at timestamptz not null default now(),
  constraint no_self_message check (sender_id <> receiver_id)
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
declare chosen text;
begin
  chosen := coalesce(new.raw_user_meta_data->>'username', split_part(new.email,'@',1));
  chosen := regexp_replace(chosen, '[^a-zA-Z0-9_.-]', '', 'g');
  if char_length(chosen) < 3 then chosen := 'user_' || substr(new.id::text,1,8); end if;
  insert into public.profiles(id,username) values(new.id,chosen);
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.posts enable row level security;
alter table public.likes enable row level security;
alter table public.comments enable row level security;
alter table public.messages enable row level security;

create policy "Profiles visible to everyone" on public.profiles for select using (true);
create policy "Users update own profile" on public.profiles for update to authenticated using (auth.uid()=id) with check (auth.uid()=id and role='user');
create policy "Posts visible to everyone" on public.posts for select using (true);
create policy "Signed in users create own posts" on public.posts for insert to authenticated with check (auth.uid()=user_id);
create policy "Owners or admins delete posts" on public.posts for delete to authenticated using (auth.uid()=user_id or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));
create policy "Likes visible to everyone" on public.likes for select using (true);
create policy "Users add own likes" on public.likes for insert to authenticated with check (auth.uid()=user_id);
create policy "Users remove own likes" on public.likes for delete to authenticated using (auth.uid()=user_id);
create policy "Comments visible to everyone" on public.comments for select using (true);
create policy "Signed in users comment as self" on public.comments for insert to authenticated with check (auth.uid()=user_id);
create policy "Users delete own comments" on public.comments for delete to authenticated using (auth.uid()=user_id);
create policy "Users see their own messages" on public.messages for select to authenticated using (auth.uid()=sender_id or auth.uid()=receiver_id);
create policy "Users send as self" on public.messages for insert to authenticated with check (auth.uid()=sender_id);
create policy "Sender deletes own messages" on public.messages for delete to authenticated using (auth.uid()=sender_id);

-- Public image bucket; upload is restricted to a folder named with the uploader's auth UID.
insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('post-images','post-images',true,5242880,array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update set public=true,file_size_limit=5242880,allowed_mime_types=excluded.allowed_mime_types;
create policy "Public can view post images" on storage.objects for select using (bucket_id='post-images');
create policy "Users upload into own folder" on storage.objects for insert to authenticated
with check (bucket_id='post-images' and (storage.foldername(name))[1]=auth.uid()::text);
create policy "Users delete own images" on storage.objects for delete to authenticated
using (bucket_id='post-images' and (storage.foldername(name))[1]=auth.uid()::text);

